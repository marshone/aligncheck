package main

import (
	"os"
	"path/filepath"
	"reflect"
	"strings"
	"testing"
)

func writeFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

const models = `package models

type Plain struct{ ID int64 }

type (
	Grouped struct{ Name string }
	Alias   = Plain
	Number  int
)

type Generic[T any] struct{ V T }

func f() {
	type local struct{ X int }
	_ = local{}
}
`

func TestGenerateRegistersTopLevelStructs(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "models.go"), models)

	res, err := generate(dir, "struct_alignment", false)
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{"Grouped", "Plain"}; !reflect.DeepEqual(res.Structs, want) {
		t.Errorf("structs = %v, want %v", res.Structs, want)
	}
	if want := []string{"Generic"}; !reflect.DeepEqual(res.Skipped, want) {
		t.Errorf("skipped = %v, want %v", res.Skipped, want)
	}

	data, err := os.ReadFile(res.Path)
	if err != nil {
		t.Fatal(err)
	}
	src := string(data)
	for _, want := range []string{
		signature + "\n",
		"// Code generated by aligncheck gen",
		"package models",
		`"Grouped": Grouped{},`,
		`"Plain":   Plain{},`,
		"aligncheck.AssertAllInPackageAligned(t, registry)",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("generated file is missing %q:\n%s", want, src)
		}
	}
}

func TestGenerateOverwriteRules(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "models.go"), models)

	if _, err := generate(dir, "struct_alignment", false); err != nil {
		t.Fatal(err)
	}
	if _, err := generate(dir, "struct_alignment", false); err == nil {
		t.Error("expected an error when the generated file exists without -f")
	}
	if _, err := generate(dir, "struct_alignment", true); err != nil {
		t.Errorf("-f should overwrite a generated file: %v", err)
	}

	// A hand-written file is never overwritten, even with -f.
	writeFile(t, filepath.Join(dir, "mine_test.go"), "package models\n")
	if _, err := generate(dir, "mine", true); err == nil {
		t.Error("expected a refusal to overwrite a hand-written file")
	}
}

func TestGenerateRejectsSecondTestStructAlignments(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "models.go"), models)
	writeFile(t, filepath.Join(dir, "existing_test.go"),
		"package models\n\nimport \"testing\"\n\nfunc TestStructAlignments(t *testing.T) {}\n")

	_, err := generate(dir, "struct_alignment", false)
	if err == nil || !strings.Contains(err.Error(), "already declares TestStructAlignments") {
		t.Errorf("expected a duplicate-test error, got %v", err)
	}
}

func TestGenerateWithoutStructsWritesNothing(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "doc.go"), "package empty\n")

	res, err := generate(dir, "struct_alignment", false)
	if err != nil || res.Path != "" {
		t.Errorf("expected no file and no error, got path=%q err=%v", res.Path, err)
	}
}

func TestFindGenerated(t *testing.T) {
	root := t.TempDir()
	pkg := filepath.Join(root, "pkg")
	hidden := filepath.Join(root, ".cache")
	for _, d := range []string{pkg, hidden} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	writeFile(t, filepath.Join(pkg, "models.go"), models)
	res, err := generate(pkg, "struct_alignment", false)
	if err != nil {
		t.Fatal(err)
	}
	writeFile(t, filepath.Join(pkg, "other_test.go"), "package models\n")
	writeFile(t, filepath.Join(hidden, "x_test.go"), signature+"\npackage x\n")

	found, err := findGenerated(root)
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{res.Path}; !reflect.DeepEqual(found, want) {
		t.Errorf("found = %v, want %v", found, want)
	}
}
